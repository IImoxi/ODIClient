inline bool minecraft_build_matches(const unsigned char* note) {
    const unsigned char header[] = {4,0,0,0,20,0,0,0,3,0,0,0,'G','N','U',0};
    for (unsigned int i = 0; i < sizeof(header); ++i)
        if (note[i] != header[i]) return false;
    for (unsigned int i = 0; i < sizeof(minecraft_build::current::buildId); ++i)
        if (note[16 + i] != minecraft_build::current::buildId[i]) return false;
    return true;
}
